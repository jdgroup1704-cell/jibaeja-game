# 폰: 전장이 화면 세로의 48%↑ · 전장 위 단추 · 글자 상자가 가린 넓이 평균 22%↓ / 두 화면: 몸끼리 30%↑ 포개진 짝 평균 10%↓(14:40 판 폰 18% — 적끼리 69%)
import sys, json
bad = []; P = json.loads(sys.argv[1]); C = json.loads(sys.argv[2])
for R in (P, C):
    if R.get('오류'): bad.append(f"{R['화면']}: 페이지 오류 {R['오류']}")
    if R['몸포개짐평균'] > 10: bad.append(f"{R['화면']}: 몸 포개짐 평균 {R['몸포개짐평균']}% (기준 10↓)")
if P['전장높이비율'] < 48: bad.append(f"폰: 전장 높이 {P['전장높이비율']}% (기준 48↑)")
if P['가림평균'] > 22: bad.append(f"폰: 전장 가림 평균 {P['가림평균']}% (기준 22↓)")
for b in bad: print('  ✗ 답답함: ' + b)
if not bad: print(f"  답답함 통과: 폰 전장 {P['전장높이비율']}% · 가림 {P['가림평균']}%(최대 {P['가림최대']}) · 포개짐 {P['몸포개짐평균']}% / PC 포개짐 {C['몸포개짐평균']}%")
sys.exit(1 if bad else 0)
