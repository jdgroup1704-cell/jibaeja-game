# 관문 ㉜(11-16 16:12~16:18 대표님 「보스 때릴 때는 보스가 보이지도 않고」 · 「잔상 · 검수 프로그램 잘 안 해??」 · 「계속 저쪽에서만 싸워? 저놈들이 더 세면 밀리고」)
# ① 맞붙는 줄: 일반 싸움 30초 동안 120↑ 움직임 · 보스에 뒤처지면 처음보다 80↑ 뒤로 · 앞서면 40↑ 앞으로
# ② 잔상: 반투명(0.12~0.8) 캐릭터 그림이 화면 왼쪽 절반(우리 편 쪽)에 같은 자리로 1.5초 넘게 남은 것 0
# ③ 보스: 몸이 전장 안에 80%↑ 보임 · 단추 · 말풍선에 가린 것 15%↓(폰 · PC)
import sys, json
bad = []
F = json.loads(sys.argv[1]); J = json.loads(sys.argv[2]); B = [json.loads(a) for a in sys.argv[3:5]]
n = F.get('일반'); s = F.get('보스느림'); q = F.get('보스빠름')
if not n or n['최대'] - n['최소'] < 120: bad.append(f"일반 싸움 줄 움직임 {n and n['최대'] - n['최소']} (기준 120↑)")
if not s or s['처음'] - s['끝'] < 80: bad.append(f"보스에 뒤처질 때 밀림 {s and s['처음'] - s['끝']} (기준 80↑)")
if not q or q['끝'] - q['처음'] < 40: bad.append(f"보스를 앞설 때 밀고 나감 {q and q['끝'] - q['처음']} (기준 40↑)")
left = [x for x in J['잔상'] if int(x[0].split('@')[1].split(',')[0]) * 30 < 360]
if left: bad.append(f"왼쪽(우리 편 쪽) 잔상 {left[:3]}")
for R in B:
    if R.get('오류'): bad.append(f"{R['화면']}: 페이지 오류 {R['오류']}")
    if R['보임최저'] < 80: bad.append(f"{R['화면']}: 보스 보임 최저 {R['보임최저']}%")
    if R['가림평균'] > 15: bad.append(f"{R['화면']}: 보스가 단추 · 말풍선에 가림 {R['가림평균']}%")
for b in bad: print('  ✗ 움직임 · 잔상 · 보스: ' + b)
if not bad: print(f"  움직임 · 잔상 · 보스 통과: 일반 줄 {n['최소']}~{n['최대']} · 보스 뒤처짐 {s['처음']}→{s['끝']} · 앞섬 {q['처음']}→{q['끝']} · 왼쪽 잔상 0 · 보스 보임 {B[0]['보임최저']}%/{B[1]['보임최저']}% · 가림 {B[0]['가림평균']}%/{B[1]['가림평균']}%")
sys.exit(1 if bad else 0)
