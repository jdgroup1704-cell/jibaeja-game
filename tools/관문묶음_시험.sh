# bash 관문묶음_시험.sh → 순서 줄을 ✅로 적고 그 관문이 실패하면 진짜 막히는지(막혀야 1, 아직이면 통과 0)
T=/tmp/묶음시험; mkdir -p $T; P=0
sed 's/| 24 | 🔶 |/| 24 | ✅ |/' ../작업순서.md > $T/q.md
python3 관문묶음.py $T/q.md ⑨ 1 > $T/o; [ $? = 1 ] && echo "  맞음(막힘): #1을 ✅로 적고 ⑨ 실패 — $(cat $T/o)" || { echo "  ✗ 안 막힘"; P=1; }
python3 관문묶음.py ../작업순서.md ⑨ 1 > $T/o; [ $? = 0 ] && echo "  맞음(알림만): #1 아직 🔶 — $(cat $T/o)" || { echo "  ✗ 대조군 막힘"; P=1; }
python3 관문묶음.py $T/q.md ⑨ 0 > $T/o; [ $? = 0 ] && echo "  맞음(통과): ✅이고 ⑨ 통과" || { echo "  ✗ 통과가 막힘"; P=1; }
[ $P = 0 ] && echo "관문묶음 시험 통과" || { echo "관문묶음 시험 실패"; exit 1; }
