# bash 순서검사_시험.sh → 순서검사.py가 진짜 막는지(틀린 값 3개는 실패해야, 맞는 값 2개는 통과해야)
T=/tmp/순서시험; mkdir -p $T; Q=../작업순서.md; P=0
t(){ printf '%s\n' "$2" > $T/j.md; python3 순서검사.py ${3:-$Q} $T/j.md > $T/o.txt; r=$?; if [ "$r" = "$1" ]; then echo "  맞음($( [ $1 = 0 ] && echo 통과 || echo 막힘)): $4 — $(grep -E '실패|이번' $T/o.txt | head -1)"; else echo "  ✗ 틀림: $4"; P=1; fi; }
t 1 "- [x] 🤖 (19:40) 별 연출 [순서 #5]" "" "맨 위(#1)를 건너뛰고 #5"
t 1 "- [x] 🤖 (19:40) 별 연출" "" "[순서 #N] 없음"
sed 's/| 7 | 🔶 순서/| 30 | 🔶 순서/; s/| 7 | 🔶 |/| 30 | 🔶 |/' $Q > $T/q.md; t 1 "- [x] 🤖 (19:40) 타격 [순서 #1]" $T/q.md "#3이 말씀 30번인데 #2(13번) 밑에 있음"
t 0 "- [x] 🤖 (19:40) 타격 리듬 [순서 #1]" "" "맨 위 #1 (대조군)"
t 0 "- [x] 🤖 (19:40) 멈춤 고침 [순서 #4] [예외: 멈춤 버그]" "" "예외 표시 (대조군)"
[ $P = 0 ] && echo "순서검사 시험 통과" || { echo "순서검사 시험 실패"; exit 1; }
