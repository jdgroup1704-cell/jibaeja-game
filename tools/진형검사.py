# python3 진형검사.py '<진형재기.js 결과 JSON>' → 관문 ⑲ 진형 고정 자리(순서 #9 · 11-16 00:25 · 00:33 대표님)
# 기준: 다 선 진형(소환수 3↑ · 영웅 4)에서 몸 겹침 프레임 5% 이하 · 발자리 겹침 2% 이하 · 자기 칸 벗어남 90% 값 25 이하 · 병과 바뀜 0
#       앞줄이 서 있을 때 영웅이 맞은 횟수 2 이하 · 앞줄을 무너뜨리면 2.8초 안에 적이 60 넘게 들어오고 영웅이 1번 넘게 맞음 · 화면 오류 0
import json, sys
r = json.loads(sys.argv[1]); b = []
pc = lambda v: int(str(v).rstrip('%')) if str(v) not in ('-', 'None') else 0
if r.get('다선진형_소환수', 0) < 3: b.append(f"다 선 진형에 소환수 {r.get('다선진형_소환수')}뿐(쓰러짐이 너무 잦음)")
if pc(r['다선진형_몸겹침']) > 5: b.append(f"몸 겹침 {r['다선진형_몸겹침']} {r.get('다선진형_예')}")
if pc(r['다선진형_자리겹침']) > 2: b.append(f"발자리 겹침 {r['다선진형_자리겹침']}")
if (r.get('자리벗어남_90') or 0) > 25: b.append(f"자리 벗어남 90% {r['자리벗어남_90']} (최대 {r.get('최대_예')})")
if r.get('병과바뀜'): b.append(f"병과 바뀜 {r['병과바뀜']}번")
if r.get('영웅맞음_앞줄있을때', 0) > 2: b.append(f"앞줄이 있는데 영웅이 맞음 {r['영웅맞음_앞줄있을때']}번")
m = r.get('무너짐') or {}
if not m or ((m.get('적_앞끝_전', 0) - m.get('적_가장깊이', 0)) < 60 and m.get('영웅맞음', 0) < 3) or m.get('영웅맞음', 0) < 1:   # 11-16 17:2x: 근접 영웅 하나가 앞줄 가운데에 서게 바뀜(대표님 15:57) → 앞줄이 무너지면 그 영웅이 막아서며 맞음(3번↑)도 인정
  b.append(f'앞줄이 무너져도 적이 영웅까지 안 옴 {m}')
if r.get('오류'): b.append(f"화면 오류 {r['오류']}")
print('  ✗ 진형: ' + ' · '.join(b) if b else f"  진형 통과: 몸 겹침 {r['다선진형_몸겹침']} · 발자리 겹침 {r['다선진형_자리겹침']} · 벗어남 90% {r['자리벗어남_90']} · 병과 바뀜 0 · 무너지면 적 {m.get('적_앞끝_전')}→{m.get('적_가장깊이')} · 영웅 맞음 {m.get('영웅맞음')}")
sys.exit(1 if b else 0)
